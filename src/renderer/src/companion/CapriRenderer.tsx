/**
 * Tallow on screen: a crow drawn from frame sequences rendered from the CC0 Pixor crow model
 * (tools/crow-art). Every companion state, and Tallow's own moods (lean, droop, love, fluff, alarm),
 * has its own loop. The component keeps Tallow's name and props so the rest of the app is unchanged.
 */
import { effectsVolume, glitchSoundOn } from '../utils/soundSettings'
import { localizeLine } from '../../../shared/lines'
import { getLineLanguage } from '../utils/lineLanguage'
import React, { useState, useEffect, useMemo, useRef } from 'react'
import { CompanionEmotionState, useCompanionStore } from '../stores/useCompanionStore'
import flapSound from '../assets/sounds/flap.wav'
import alarmSound from '../assets/sounds/alarm.wav'
import mumbleSound from '../assets/sounds/mumble.wav'
import kawSound from '../assets/sounds/kaw.wav'
import rattleSound from '../assets/sounds/rattle.wav'
import crowFrontImg from '../assets/crow/idle_front/idle_front.png'

interface CapriRendererProps {
  state: CompanionEmotionState
  onClick?: (e: React.MouseEvent<HTMLDivElement>) => void
  className?: string
  overrideDirection?: 'left' | 'right'
  noShadow?: boolean
  isGamingMode?: boolean
}

const SOUNDS: Record<string, string> = { flap: flapSound, alarm: alarmSound, mumble: mumbleSound, kaw: kawSound, rattle: rattleSound }
let activeAudio: HTMLAudioElement | null = null

/** Tallow's caws (assets/sounds, generated by the Crow Companion proof of concept) */
export const playCrowSound = (name: string | null | undefined, volume = 0.7): void => {
  if (!name || !SOUNDS[name]) return
  try {
    if (activeAudio) {
      activeAudio.pause()
      activeAudio.currentTime = 0
    }
    const audio = new Audio(SOUNDS[name])
    audio.volume = Math.min(1, volume * effectsVolume())
    activeAudio = audio
    audio.play().catch(() => {})
  } catch {
    // no audio device
  }
}

/** A soft wing flap when he changes pose (the "transition sound" setting) */
const playFlap = (): void => {
  if (!glitchSoundOn()) return
  playCrowSound('flap', 0.35)
}

/** Startled: alarm caws (kept under Tallow's old export name) */
export const playMultiGlitchSound = (count = 2, intervalMs = 260): void => {
  if (!glitchSoundOn()) return
  for (let i = 0; i < Math.max(1, Math.min(count, 3)); i++) setTimeout(() => playCrowSound('alarm', 0.55), i * intervalMs)
}

/** Petting: a contented mumble */
export const playPetChirpSound = (): void => {
  playCrowSound('mumble', 0.6)
}

const assetModules = import.meta.glob<{ default: string }>('../assets/crow/*/*.{png,gif,webp}', { eager: true })

const STATES = [
  'idle', 'idle_front', 'standing', 'walking', 'thinking', 'working', 'happy', 'talking', 'sleep', 'curious', 'ojos', 'capri2',
  'closed', 'asustada', 'lean', 'droop', 'love', 'fluff', 'alarm'
] as const

const FPS: Record<string, number> = {
  walking: 9, talking: 8, happy: 10, sleep: 4, curious: 6, standing: 6, ojos: 7, capri2: 12, closed: 8, asustada: 12,
  lean: 6, droop: 5, love: 7, fluff: 8, alarm: 12, idle: 6, idle_front: 6
}

export const CapriRenderer: React.FC<CapriRendererProps> = ({
  state,
  onClick,
  className = '',
  overrideDirection,
  noShadow = false
}) => {
  const { renderMode, direction: storeDirection, isCatchGameActive } = useCompanionStore()
  const direction = overrideDirection || storeDirection
  const [frame, setFrame] = useState(0)
  const [flapping, setFlapping] = useState(false)
  const lastState = useRef<CompanionEmotionState | null>(null)

  const { framesByState, webpByState } = useMemo(() => {
    const indexed: Record<string, { index: number; url: string }[]> = {}
    const webp: Record<string, string> = {}
    for (const st of STATES) indexed[st] = []
    for (const [p, mod] of Object.entries(assetModules)) {
      const url = (mod as { default: string }).default
      const fm = p.match(/\/crow\/([^/]+)\/frame_(\d+)\.png$/)
      if (fm) {
        ;(indexed[fm[1]] ||= []).push({ index: parseInt(fm[2], 10), url })
        continue
      }
      const single = p.match(/\/crow\/([^/]+)\/[^/]+\.png$/)
      if (single) {
        ;(indexed[single[1]] ||= []).push({ index: 0, url })
        continue
      }
      const anim = p.match(/\/crow\/([^/]+)\/[^/]+\.webp$/)
      if (anim) webp[anim[1]] = url
    }
    const frames: Record<string, string[]> = {}
    for (const [st, list] of Object.entries(indexed)) frames[st] = list.sort((a, b) => a.index - b.index).map((x) => x.url)
    return { framesByState: frames, webpByState: webp }
  }, [])

  // thinking/working: he peers at it. ojos2 was Tallow's eye video: his close-up stare
  const effective = state === 'thinking' || state === 'working' ? 'curious' : state === 'ojos2' ? 'ojos' : state
  const frames = framesByState[effective]?.length ? framesByState[effective] : framesByState.idle
  const fps = effective === 'walking' && isCatchGameActive ? 14 : FPS[effective] || 6

  useEffect(() => {
    setFrame(0)
    if (frames.length <= 1) return
    const timer = setInterval(() => setFrame((f) => (f + 1) % frames.length), Math.round(1000 / fps))
    return () => clearInterval(timer)
  }, [effective, frames.length, fps])

  // A little hop and a wing flap on every change of pose
  useEffect(() => {
    if (lastState.current === state) return
    const first = lastState.current === null
    lastState.current = state
    setFlapping(true)
    if (state === 'asustada' || state === 'alarm') playMultiGlitchSound(2, 260)
    else if (!first) playFlap()
    const t = setTimeout(() => setFlapping(false), 320)
    return () => clearTimeout(t)
  }, [state])

  const src =
    effective === 'idle_front'
      ? crowFrontImg
      : renderMode === 'webp' && webpByState[effective]
        ? webpByState[effective]
        : frames[frame] || frames[0]

  const shadow = noShadow ? 'none' : 'drop-shadow(0 6px 6px rgba(0, 0, 0, 0.35))'
  const style = useMemo((): React.CSSProperties => {
    switch (effective) {
      case 'idle':
      case 'idle_front':
      case 'standing':
        return { filter: shadow }
      case 'sleep':
        return { filter: `${shadow} saturate(0.85)` }
      case 'closed':
      case 'fluff':
        return { filter: noShadow ? 'none' : 'drop-shadow(0 0 6px rgba(224, 88, 60, 0.55))' }
      case 'walking':
        return {
          filter: isCatchGameActive && !noShadow ? 'drop-shadow(0 0 6px rgba(217, 161, 74, 0.9))' : shadow,
          transition: 'transform 0.15s ease'
        }
      default:
        return { filter: shadow }
    }
  }, [effective, noShadow, isCatchGameActive, shadow])

  // The close-up and front-facing poses look straight at you, so they are never mirrored
  const mirrored = effective !== 'idle_front' && effective !== 'ojos' && direction === 'right'

  return (
    <div
      onClick={onClick}
      data-capri-art
      className={`relative inline-flex items-center justify-center cursor-pointer select-none ${className}`}
      style={{ width: '100%', height: '100%', WebkitAppRegion: 'no-drag' } as React.CSSProperties}
      title={
        isCatchGameActive
          ? localizeLine('CLICK TO CATCH TALLOW!', getLineLanguage())
          : 'Tallow // Shift+Drag to move | Click for the nest | Ctrl+Click to talk'
      }
    >
      {!noShadow && isCatchGameActive && (
        <div
          className="absolute inset-4 rounded-full pointer-events-none animate-ping"
          style={{ background: 'radial-gradient(circle, rgba(217, 161, 74, 0.35) 0%, transparent 70%)' }}
        />
      )}
      {src ? (
        <div
          className="relative w-full h-full flex items-center justify-center overflow-visible"
          style={{ transform: mirrored ? 'scaleX(-1)' : 'scaleX(1)', transition: 'transform 0.15s ease' }}
        >
          <img
            key={effective}
            src={src}
            alt={`Tallow (${effective})`}
            draggable={false}
            className={flapping ? 'crow-pose-change' : ''}
            style={{ ...style, width: '100%', height: '100%', objectFit: 'contain', pointerEvents: 'none', userSelect: 'none', imageRendering: 'auto' }}
          />
        </div>
      ) : (
        <div className="text-xs text-amber-300 font-mono p-4 text-center">[Tallow is landing…]</div>
      )}
    </div>
  )
}
